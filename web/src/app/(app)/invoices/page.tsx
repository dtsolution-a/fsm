'use client';
import RowActions from '@/components/RowActions';
import { useRouter } from 'next/navigation';
import { useState } from 'react';
import LineEditor, { emptyLine, type Line } from '@/components/LineEditor';
import { MachinePicker } from '@/components/pickers';
import { Badge, Button, Card, ErrorNote, Field, Input, Modal, PageHeader, Pagination, Select, Spinner, Stat, Table, Td } from '@/components/ui';
import { fmtDate, fmtMoney, post, qs } from '@/lib/api';
import { useAuth } from '@/lib/auth';
import { invLabel, invTone } from '@/lib/billing';
import { useDebounced, useFetch } from '@/lib/hooks';


export default function Invoices() {
  const { user } = useAuth();
  const router = useRouter();
  const [status, setStatus] = useState('');
  const [search, setSearch] = useState('');
  const [page, setPage] = useState(1); const [limit, setLimit] = useState(20);
  const q = useDebounced(search);
  const [auto, setAuto] = useState(false);
  const { data, loading, error, reload } = useFetch<any>(`/invoices${qs({ status: auto ? '' : status, auto: auto ? 'true' : '', search: q, page, limit })}`);
  const drafts = useFetch<any>('/invoices?auto=true&limit=1');
  const out = useFetch<any>('/billing/outstanding');
  const [creating, setCreating] = useState(false);
  const can = user?.role === 'admin' || user?.role === 'ga_head';

  return (
    <>
      <PageHeader title="Invoices" subtitle="Drafts are prepared automatically when a job is closed. Fill in the rates, issue, share and collect payment."
        actions={can && <Button onClick={() => setCreating(true)}>+ New invoice</Button>} />
      <div className="mb-4 grid grid-cols-2 gap-3 md:grid-cols-4">
        <Stat label="Receivable" value={fmtMoney(out.data?.totalBalance ?? 0)} sub={`${out.data?.clients?.length ?? 0} clients owe money`} />
        <Stat label="Overdue" value={fmtMoney(out.data?.totalOverdue ?? 0)} tone={out.data?.totalOverdue ? 'red' : 'green'} sub="past due date" />
      </div>
      {(drafts.data?.meta?.total ?? 0) > 0 && (
        <button onClick={() => { setAuto(true); setPage(1); }} className={`mb-4 flex w-full items-center justify-between rounded-lg border px-4 py-3 text-left text-sm ${auto ? 'border-indigo-300 bg-indigo-50' : 'border-amber-200 bg-amber-50 hover:bg-amber-100'}`}>
          <span><b>{drafts.data.meta.total} draft bill{drafts.data.meta.total > 1 ? 's' : ''} prepared automatically</b> when jobs were completed. Check the amounts and issue them.</span><span className="font-medium text-indigo-700">{auto ? 'Showing' : 'Review →'}</span>
        </button>
      )}
      <Card>
        <div className="mb-4 flex flex-wrap items-center gap-3">
          <div className="flex rounded-md border border-slate-300 bg-white p-0.5 text-sm">
            <button onClick={() => { setAuto(false); setPage(1); }} className={`rounded px-3 py-1 ${!auto ? 'bg-indigo-600 text-white' : 'text-slate-600'}`}>All invoices</button>
            <button onClick={() => { setAuto(true); setPage(1); }} className={`rounded px-3 py-1 ${auto ? 'bg-indigo-600 text-white' : 'text-slate-600'}`}>Auto drafts{drafts.data?.meta?.total ? ` (${drafts.data.meta.total})` : ''}</button>
          </div>
          <Input className="max-w-xs" placeholder="Search invoice no. or client…" value={search} onChange={(e) => { setSearch(e.target.value); setPage(1); }} />
          <Select className="w-48" disabled={auto} value={status} onChange={(e) => { setStatus(e.target.value); setPage(1); }}>
            <option value="">All invoices</option><option value="draft">Draft (needs rates)</option><option value="unpaid">Unpaid</option><option value="partially_paid">Partially paid</option><option value="overdue">Overdue</option><option value="paid">Paid</option><option value="cancelled">Cancelled</option>
          </Select>
        </div>
        {error && <ErrorNote message={error} />}
        {loading && !data ? <Spinner /> : <>
          <Table head={['Invoice', 'Client', 'Job', 'Issued', 'Due', 'Total', 'Paid', 'Status', 'Actions']} empty={data?.data.length === 0}>
            {data?.data.map((i: any) => (
              <tr key={i.id} className="cursor-pointer" onClick={() => router.push(`/invoices/${i.id}`)}>
                <Td className="whitespace-nowrap font-medium text-indigo-700">{i.invoiceNumber}{i.autoGenerated && i.status === 'draft' && <span className="ml-2"><Badge tone="blue">Auto</Badge></span>}</Td>
                <Td>{i.client.companyName}</Td><Td className="text-xs">{i.job?.jobNumber || '—'}</Td>
                <Td className="whitespace-nowrap text-xs">{fmtDate(i.issuedAt)}</Td><Td className="whitespace-nowrap text-xs">{fmtDate(i.dueDate)}</Td>
                <Td className="whitespace-nowrap font-medium tabular-nums">{fmtMoney(i.totalAmount)}</Td>
                <Td className="whitespace-nowrap tabular-nums">{fmtMoney(i.paidAmount)}</Td>
                <Td><Badge tone={invTone(i.status)}>{invLabel(i.status)}</Badge>{i.isAmc && <span className="ml-1"><Badge tone="blue">AMC</Badge></span>}</Td>
                  <Td className="text-right"><RowActions entity="invoices" id={i.id} viewHref={`/invoices/${i.id}`} onChanged={reload} /></Td>
              </tr>
            ))}
          </Table>
          <Pagination meta={data?.meta} onPage={setPage} onLimit={(n) => { setLimit(n); setPage(1); }} />
        </>}
      </Card>
      <NewInvoice open={creating} onClose={() => setCreating(false)} onDone={(id) => router.push(`/invoices/${id}`)} />
    </>
  );
}

function NewInvoice({ open, onClose, onDone }: { open: boolean; onClose(): void; onDone(id: string): void }) {
  const [m, setM] = useState({ clientId: '', siteProductId: '', clientName: '' });
  const [lines, setLines] = useState<Line[]>([emptyLine()]);
  const [err, setErr] = useState(''); const [busy, setBusy] = useState(false);
  async function submit(e: React.FormEvent) {
    e.preventDefault(); setBusy(true); setErr('');
    try { const r = await post('/invoices', { clientId: m.clientId, lines: lines.map(({ note, ...l }) => l) }); onDone(r.id); } catch (e: any) { setErr(e.message); } finally { setBusy(false); }
  }
  return (
    <Modal open={open} onClose={onClose} title="New invoice (not from a job)" wide>
      <form onSubmit={submit} className="space-y-3">
        <MachinePicker onChange={setM} />
        <LineEditor lines={lines} onChange={setLines} />
        <p className="text-xs text-slate-400">For a finished job, open the job and use “Invoice” — it fills in the parts and the contract cover for you.</p>
        {err && <ErrorNote message={err} />}
        <div className="flex justify-end gap-2"><Button type="button" variant="secondary" onClick={onClose}>Cancel</Button><Button type="submit" disabled={busy || !m.clientId || lines.some((l) => !l.description.trim())}>Create draft</Button></div>
      </form>
    </Modal>
  );
}
